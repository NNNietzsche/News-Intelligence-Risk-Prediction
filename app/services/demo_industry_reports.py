def demo_source_list_html(report: dict[str, Any]) -> str:
    """将固定材料明确展示为来源，防止演示稿被误认为实时抓取结果。"""
    sources = report.get("demo_sources") or []
    items = []
    for source in sources:
        label = escape(str(source.get("label") or "参考材料"))
        note = escape(str(source.get("note") or ""))
        href = str(source.get("url") or "").strip()
        if href.startswith(("https://", "http://")):
            items.append(
                f'<li><a href="{escape(href)}" target="_blank" rel="noopener noreferrer">{label}</a>'
                f'{("：" + note) if note else ""}</li>'
            )
        else:
            items.append(f"<li>{label}{('：' + note) if note else ''}</li>")
    return (
        '<section class="report-section report-source-list">'
        '<h2>报告口径与来源</h2>'
        '<p>本报告为现场演示固定版本，未在生成时调用外部检索或大模型；数值与判断仅基于以下已提供材料。</p>'
        '<ol class="report-source-list-items">' + "".join(items) + "</ol></section>"
    )


def demo_report_html(report: dict[str, Any]) -> str:
    """渲染用户确认的固定原文；避免现场演示时被模型重写或压缩。"""
    title = escape(str(report.get("title") or "行业年度授信分析"))
    parts = [f'<h1 class="report-title">{title}</h1>']
    for block in report.get("verbatim_sections") or []:
        heading = escape(str(block.get("heading") or ""))
        if heading:
            level = "h3" if heading.startswith("（") else "h2"
            parts.append(f"<{level}>{heading}</{level}>")
        for paragraph in block.get("paragraphs") or []:
            parts.append(f'<p>{escape(str(paragraph))}</p>')
        table = block.get("table")
        if table:
            headers = table.get("headers") or []
            rows = table.get("rows") or []
            parts.append('<div class="report-table-wrap"><table class="report-table"><thead><tr>')
            parts.extend(f"<th>{escape(str(value))}</th>" for value in headers)
            parts.append("</tr></thead><tbody>")
            for row in rows:
                parts.append("<tr>")
                parts.extend(f"<td>{escape(str(value))}</td>" for value in row)
                parts.append("</tr>")
            parts.append("</tbody></table></div>")
        for note in block.get("notes") or []:
            parts.append(f'<p class="hint">{escape(str(note))}</p>')
    return "\n".join(parts)


