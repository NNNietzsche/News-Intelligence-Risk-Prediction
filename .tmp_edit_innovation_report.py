def apply_chinese_font(document: Document) -> None:
    """Use an installed CJK font so Word and headless rendering show Chinese text."""
    font_name = "Noto Sans CJK SC"
    for style_name in ("Normal", "Title", "Subtitle", "Heading 1", "Heading 2"):
        try:
            style = document.styles[style_name]
        except KeyError:
            continue
        style.font.name = font_name
        style._element.rPr.rFonts.set(qn("w:eastAsia"), font_name)
    for paragraph in document.paragraphs:
        for run in paragraph.runs:
            run.font.name = font_name
            run._element.rPr.rFonts.set(qn("w:ascii"), font_name)
            run._element.rPr.rFonts.set(qn("w:hAnsi"), font_name)
            run._element.rPr.rFonts.set(qn("w:eastAsia"), font_name)


def main() -> None:
    document = Document(SOURCE)
    unmatched = set(REPLACEMENTS)
    for paragraph in document.paragraphs:
        original = paragraph.text.strip()
        for prefix, replacement in REPLACEMENTS.items():
            if original.startswith(prefix):
                paragraph.text = replacement
                unmatched.discard(prefix)
                break
    if unmatched:
        raise RuntimeError(f"未找到需替换段落：{sorted(unmatched)}")
    apply_chinese_font(document)
    document.core_properties.author = "DingJiaye"
    document.core_properties.comments = "按前台主动风险、公开信息和AI智能体方向修订"
    document.save(OUTPUT)
    print(OUTPUT)


if __name__ == "__main__":
    main()
